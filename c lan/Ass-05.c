
#include <stdio.h>

int main()
{
// Data Type
    int A = 10;
    long l = 1212;
    char ch = 'a';
    float f = 1.2;
    double d = 12.45;

    printf("A = %d\n", A);
    printf("l = %ld\n", l);
    printf("ch = %c\n", ch);
    printf("f = %f\n", f);
    printf("d = %lf\n", d);
    return 0;
}